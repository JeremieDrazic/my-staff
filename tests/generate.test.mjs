import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { loadRepo } from '../src/model.mjs'
import { buildManifests, writeManifests, checkManifests } from '../src/manifest.mjs'
import { buildSyncPlan, writeSync, checkSync } from '../src/sync.mjs'
import { renderDomains, renderStats, buildReadmes } from '../src/readme.mjs'
import { makeFixture, domainManifest, skillFile, codes } from './helpers.mjs'

const twoDomains = {
  'domains/craft/domain.json': domainManifest('craft'),
  'domains/craft/skills/do-a-thing/SKILL.md': skillFile('do-a-thing'),
  'domains/retired/domain.json': domainManifest('retired', { status: 'deprecated' }),
}

test('every live domain becomes a marketplace entry, and a deprecated one does not', () => {
  const repo = loadRepo(makeFixture(twoDomains))
  const marketplace = JSON.parse(
    buildManifests(repo).find((file) => file.path === '.claude-plugin/marketplace.json').content,
  )
  assert.deepEqual(
    marketplace.plugins.map((plugin) => plugin.name),
    ['craft'],
  )
  assert.equal(marketplace.plugins[0].source, './domains/craft')
})

test('a domain gets both plugin manifests, in the places each runtime reads', () => {
  const repo = loadRepo(makeFixture(twoDomains))
  const paths = buildManifests(repo).map((file) => file.path)
  assert.ok(paths.includes('domains/craft/.claude-plugin/plugin.json'))
  assert.ok(paths.includes('domains/craft/plugin.json'))
  assert.ok(paths.includes('skills.sh.json'))
})

test('manifests are reported stale until they are written, then clean', () => {
  const root = makeFixture(twoDomains)
  assert.ok(checkManifests(loadRepo(root)).length > 0)
  writeManifests(loadRepo(root))
  assert.deepEqual(checkManifests(loadRepo(root)), [])
})

/**
 * One file, not a folder: a reference reached from another reference is read
 * partially, so a skill that linked an index would never see the criteria.
 */
test('a declared checklist is copied into the skill as one file, with a header naming its source', () => {
  const root = makeFixture({
    'domains/craft/domain.json': domainManifest('craft'),
    'domains/craft/checklists/review/00-index.md': '# Review\n\n## Sections\n\n- [01-a.md](01-a.md)\n',
    'domains/craft/checklists/review/01-a.md': '# A — the first pass\n\nCriterion.\n',
    'domains/craft/skills/do-a-thing/SKILL.md': skillFile('do-a-thing', {
      extra: 'metadata:\n  checklists:\n    - review\n',
    }),
  })
  const repo = loadRepo(root)
  assert.deepEqual(buildSyncPlan(repo).map((entry) => entry.path), [
    'domains/craft/skills/do-a-thing/references/review.md',
  ])
  assert.deepEqual(codes(checkSync(repo)), ['sync/stale-checklist-copy'])

  writeSync(repo)
  const copy = readFileSync(join(root, 'domains/craft/skills/do-a-thing/references/review.md'), 'utf8')
  assert.match(copy, /Generated by `staff sync` from domains\/craft\/checklists\/review\//)
  assert.match(copy, /Criterion\./)
  // The section list becomes in-page anchors, and the section heading sits under the index.
  assert.match(copy, /## Contents\n\n- \[A — the first pass\]\(#a--the-first-pass\)/)
  assert.match(copy, /^## A — the first pass$/m)
  assert.doesNotMatch(copy, /\[01-a\.md\]/)
  assert.deepEqual(checkSync(loadRepo(root)), [])
})

test('a copy whose checklist is no longer declared is reported, then removed', () => {
  const root = makeFixture({
    'domains/craft/domain.json': domainManifest('craft'),
    'domains/craft/checklists/review/00-index.md': '# Review\n',
    'domains/craft/skills/do-a-thing/SKILL.md': skillFile('do-a-thing'),
    'domains/craft/skills/do-a-thing/references/review.md': 'stale copy\n',
  })
  assert.deepEqual(codes(checkSync(loadRepo(root))), ['sync/orphan-copy'])
  writeSync(loadRepo(root))
  assert.equal(existsSync(join(root, 'domains/craft/skills/do-a-thing/references/review.md')), false)
})

/** The shape sync used to generate. A leftover folder is an orphan, not a copy. */
test('a checklist copy left over as a folder of sections is removed', () => {
  const root = makeFixture({
    'domains/craft/domain.json': domainManifest('craft'),
    'domains/craft/checklists/review/00-index.md': '# Review\n\n- [01-a.md](01-a.md)\n',
    'domains/craft/checklists/review/01-a.md': '# A\n\nCriterion.\n',
    'domains/craft/skills/do-a-thing/SKILL.md': skillFile('do-a-thing', {
      extra: 'metadata:\n  checklists:\n    - review\n',
    }),
    'domains/craft/skills/do-a-thing/references/review/00-index.md': 'old copy\n',
    'domains/craft/skills/do-a-thing/references/review/01-a.md': 'old copy\n',
  })
  assert.deepEqual(codes(checkSync(loadRepo(root))), ['sync/stale-checklist-copy', 'sync/orphan-copy'])
  writeSync(loadRepo(root))
  assert.equal(existsSync(join(root, 'domains/craft/skills/do-a-thing/references/review')), false)
  assert.equal(existsSync(join(root, 'domains/craft/skills/do-a-thing/references/review.md')), true)
  assert.deepEqual(checkSync(loadRepo(root)), [])
})

test('the README tables are rendered from the domain manifests', () => {
  const repo = loadRepo(makeFixture(twoDomains))
  const table = renderDomains(repo)
  assert.match(table, /### Engineering/)
  assert.match(table, /`craft`/)
  assert.match(table, /~~`retired`~~/)
  assert.match(renderStats(repo), /\*\*1\*\* skills/)
})

test('only the marked blocks of the README are replaced', () => {
  const root = makeFixture({
    ...twoDomains,
    'README.md': '# Title\n\nKeep me.\n\n<!-- staff:stats -->\nold\n<!-- /staff:stats -->\n\nKeep me too.\n',
  })
  const readme = buildReadmes(loadRepo(root)).find((file) => file.path === 'README.md').content
  assert.match(readme, /Keep me\./)
  assert.match(readme, /Keep me too\./)
  assert.doesNotMatch(readme, /\nold\n/)
  assert.match(readme, /\*\*1\*\* skills/)
})
