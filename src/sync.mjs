import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, readdirSync } from 'node:fs'
import { join, relative } from 'node:path'

const header = (source) =>
  `<!-- Generated by \`staff sync\` from ${source}. Edit the source, not this copy. -->\n\n`

/**
 * A checklist is one canonical document at the domain level, because it is reviewed
 * in a pull request like any other document. It also has to travel inside each skill
 * that uses it, because a claude.ai upload only receives the skill's own folder.
 * So the copy is generated and the CI refuses a stale one.
 */
export function buildSyncPlan(repo) {
  const plan = []
  for (const domain of repo.domains) {
    for (const skill of domain.skills) {
      for (const name of skill.data?.metadata?.checklists ?? []) {
        const checklist = domain.checklists.find((candidate) => candidate.name === name)
        if (!checklist) continue
        for (const section of checklist.sections) {
          const source = relative(repo.root, join(checklist.dir, section)).split('\\').join('/')
          plan.push({
            path: relative(repo.root, join(skill.dir, 'references', name, section)).split('\\').join('/'),
            content: header(source) + readFileSync(join(checklist.dir, section), 'utf8'),
          })
        }
      }
    }
  }
  return plan
}

/** Copies under references/<checklist>/ that the plan no longer covers. */
function orphans(repo, plan) {
  const planned = new Set(plan.map((entry) => entry.path))
  const found = []
  for (const domain of repo.domains) {
    for (const skill of domain.skills) {
      const root = join(skill.dir, 'references')
      if (!existsSync(root)) continue
      for (const name of readdirSync(root)) {
        const dir = join(root, name)
        if (!domain.checklists.some((checklist) => checklist.name === name)) continue
        for (const file of readdirSync(dir)) {
          const path = relative(repo.root, join(dir, file)).split('\\').join('/')
          if (!planned.has(path)) found.push(path)
        }
      }
    }
  }
  return found
}

export function writeSync(repo) {
  const plan = buildSyncPlan(repo)
  const written = []
  for (const entry of plan) {
    const target = join(repo.root, entry.path)
    if (existsSync(target) && readFileSync(target, 'utf8') === entry.content) continue
    mkdirSync(join(target, '..'), { recursive: true })
    writeFileSync(target, entry.content)
    written.push(entry.path)
  }
  const removed = orphans(repo, plan)
  for (const path of removed) rmSync(join(repo.root, path))
  return { written, removed }
}

export function checkSync(repo) {
  const plan = buildSyncPlan(repo)
  const findings = plan
    .filter((entry) => {
      const target = join(repo.root, entry.path)
      return !existsSync(target) || readFileSync(target, 'utf8') !== entry.content
    })
    .map((entry) => ({
      level: 'error',
      code: 'sync/stale-checklist-copy',
      file: entry.path,
      message: 'Differs from the canonical checklist. Run `staff sync`.',
    }))
  for (const path of orphans(repo, plan)) {
    findings.push({ level: 'error', code: 'sync/orphan-copy', file: path, message: 'No skill declares this checklist any more. Run `staff sync`.' })
  }
  return findings
}
