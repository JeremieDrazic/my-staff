import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const header = (source) =>
  `<!-- Generated by \`staff sync\` from ${source}. Edit the source, not this copy. -->\n\n`

/** GitHub's heading anchors: lowercase, punctuation dropped, spaces to hyphens. */
function slug(heading) {
  return heading
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .trim()
    .replace(/ /g, '-')
}

/** The first ATX heading of a markdown document, without its hashes. */
function firstHeading(text) {
  const match = text.match(/^#{1,6} +(.+)$/m)
  return match ? match[1].trim() : null
}

/**
 * Pushes every heading down one level, so the sections sit under the index
 * instead of competing with it. Headings inside fenced code are left alone.
 */
function demote(text) {
  let fenced = false
  return text
    .split('\n')
    .map((line) => {
      if (/^(```|~~~)/.test(line)) fenced = !fenced
      if (fenced) return line
      return /^#{1,5} /.test(line) ? `#${line}` : line
    })
    .join('\n')
}

/** Replaces the index's section list with a table of contents of in-page anchors. */
function withContents(index, entries) {
  const contents = ['## Contents', '', ...entries.map((entry) => `- [${entry.heading}](#${slug(entry.heading)})`), ''].join('\n')
  const start = index.indexOf('## Sections')
  if (start === -1) return `${index.trimEnd()}\n\n${contents}`
  const after = index.indexOf('\n## ', start + 1)
  const tail = after === -1 ? '' : index.slice(after + 1)
  return `${index.slice(0, start)}${contents}\n${tail}`
}

/**
 * A checklist is one canonical document at the domain level, because it is reviewed
 * in a pull request like any other document. It also has to travel inside each skill
 * that uses it, because a claude.ai upload only receives the skill's own folder.
 *
 * The copy is a single file, never a folder of sections: a reference reached from
 * another reference is read partially, so a skill that linked an index would never
 * see the criteria it is supposed to be gated by. One file is one level, and one
 * level is read whole. When that file outgrows its budget the answer is two
 * checklists, not sections inside one — `staff validate` says so.
 */
export function buildSyncPlan(repo) {
  const plan = []
  for (const domain of repo.domains) {
    for (const skill of domain.skills) {
      for (const name of skill.data?.metadata?.checklists ?? []) {
        const checklist = domain.checklists.find((candidate) => candidate.name === name)
        if (!checklist) continue
        const sections = checklist.sections
          .filter((section) => section !== '00-index.md')
          .map((section) => {
            const text = readFileSync(join(checklist.dir, section), 'utf8').trim()
            return { section, heading: firstHeading(text) ?? section, body: demote(text) }
          })
        const source = `${relative(repo.root, checklist.dir).split('\\').join('/')}/`
        const parts = [header(source)]
        if (checklist.index) parts.push(`${withContents(checklist.index.raw.trim(), sections)}\n`)
        for (const entry of sections) parts.push(`\n---\n\n${entry.body}\n`)
        plan.push({
          path: relative(repo.root, join(skill.dir, 'references', `${name}.md`)).split('\\').join('/'),
          content: parts.join(''),
        })
      }
    }
  }
  return plan
}

/** Generated checklist copies the plan no longer covers, in either shape. */
function orphans(repo, plan) {
  const planned = new Set(plan.map((entry) => entry.path))
  const found = []
  for (const domain of repo.domains) {
    const names = new Set(domain.checklists.map((checklist) => checklist.name))
    for (const skill of domain.skills) {
      const root = join(skill.dir, 'references')
      if (!existsSync(root)) continue
      for (const entry of readdirSync(root)) {
        const path = join(root, entry)
        // The former shape: references/<checklist>/<section>.md. Always an orphan now.
        if (statSync(path).isDirectory()) {
          if (names.has(entry)) found.push(relative(repo.root, path).split('\\').join('/'))
          continue
        }
        const name = entry.replace(/\.md$/, '')
        const relative_ = relative(repo.root, path).split('\\').join('/')
        if (names.has(name) && !planned.has(relative_)) found.push(relative_)
      }
    }
  }
  return found
}

export function writeSync(repo) {
  const plan = buildSyncPlan(repo)
  const written = []
  for (const entry of plan) {
    const target = join(repo.root, entry.path)
    if (existsSync(target) && readFileSync(target, 'utf8') === entry.content) continue
    mkdirSync(join(target, '..'), { recursive: true })
    writeFileSync(target, entry.content)
    written.push(entry.path)
  }
  const removed = orphans(repo, plan)
  for (const path of removed) rmSync(join(repo.root, path), { recursive: true })
  return { written, removed }
}

export function checkSync(repo) {
  const plan = buildSyncPlan(repo)
  const findings = plan
    .filter((entry) => {
      const target = join(repo.root, entry.path)
      return !existsSync(target) || readFileSync(target, 'utf8') !== entry.content
    })
    .map((entry) => ({
      level: 'error',
      code: 'sync/stale-checklist-copy',
      file: entry.path,
      message: 'Differs from the canonical checklist. Run `staff sync`.',
    }))
  for (const path of orphans(repo, plan)) {
    findings.push({ level: 'error', code: 'sync/orphan-copy', file: path, message: 'No skill declares this checklist any more. Run `staff sync`.' })
  }
  return findings
}
