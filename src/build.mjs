import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, cpSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'
import { stringify } from 'yaml'
import { SPEC_KEYS, allSkills } from './model.mjs'
import { estimateTokens } from './frontmatter.mjs'

/** Project instructions are a text box, not a filesystem. Keep a pack paste-able. */
const CHATGPT_TOKEN_WARN = 8000

const CLAUDE_CODE_BODY = [
  { pattern: /!`[^`]+`/, what: 'command injection (!`…`)' },
  { pattern: /\$\{CLAUDE_(?:PLUGIN_ROOT|PROJECT_DIR)\}/, what: 'a Claude Code path variable' },
]

function freshDirectory(path) {
  rmSync(path, { recursive: true, force: true })
  mkdirSync(path, { recursive: true })
  return path
}

/**
 * claude.ai accepts six frontmatter keys and fails the upload on any other, so the zip
 * carries a stripped copy. A body feature that only works in Claude Code is refused here
 * rather than shipped: it would upload cleanly and then silently skip a step.
 */
export function buildClaudeAi(repo, { outDir = join(repo.root, 'dist', 'claude-ai') } = {}) {
  if (!hasZip()) {
    throw new Error('`zip` is not on PATH, and the claude.ai target needs it to package a skill.')
  }
  const out = freshDirectory(outDir)
  const built = []
  const refused = []

  for (const { domain, skill } of allSkills(repo)) {
    if (!skill.exists || skill.data === null) continue
    const declared = new Set(skill.data.compatibility ?? [])
    const blocker = CLAUDE_CODE_BODY.find(({ pattern }) => pattern.test(skill.body))
    if (blocker && !declared.has('claude-code')) {
      refused.push({ skill: skill.name, reason: `body uses ${blocker.what} without declaring claude-code compatibility` })
      continue
    }
    if (declared.has('claude-code') && !declared.has('claude-ai')) {
      refused.push({ skill: skill.name, reason: 'declared Claude Code-only' })
      continue
    }

    const kept = Object.fromEntries(Object.entries(skill.data).filter(([key]) => SPEC_KEYS.includes(key)))
    const dropped = Object.keys(skill.data).filter((key) => !SPEC_KEYS.includes(key))
    const staging = join(out, '.staging', skill.name)
    mkdirSync(staging, { recursive: true })
    writeFileSync(join(staging, 'SKILL.md'), `---\n${stringify(kept).trimEnd()}\n---\n${skill.body}`)
    if (existsSync(join(skill.dir, 'references'))) {
      cpSync(join(skill.dir, 'references'), join(staging, 'references'), { recursive: true })
    }

    execFileSync('zip', ['-rq', join(out, `${skill.name}.zip`), skill.name], { cwd: join(out, '.staging') })
    built.push({ domain: domain.name, skill: skill.name, dropped, file: `dist/claude-ai/${skill.name}.zip` })
  }
  rmSync(join(out, '.staging'), { recursive: true, force: true })
  return { built, refused }
}

function hasZip() {
  try {
    execFileSync('zip', ['-h'], { stdio: 'ignore' })
    return true
  } catch {
    return false
  }
}

/** One paste-able pack per domain, plus one per skill for the days you only need one. */
export function buildChatgpt(repo, { outDir = join(repo.root, 'dist', 'chatgpt') } = {}) {
  const out = freshDirectory(outDir)
  const built = []

  const preamble = (title, note) =>
    `<!-- ${title} — paste this into a ChatGPT Project's instructions. ${note} -->\n\n`

  for (const domain of repo.domains) {
    const skills = domain.skills.filter((skill) => skill.exists && skill.data)
    if (skills.length === 0) continue

    for (const skill of skills) {
      const content =
        preamble(`my-staff / ${domain.name} / ${skill.name}`, 'Generated by `staff build chatgpt`.') +
        `# ${skill.name}\n\n**Use this when:** ${skill.data.description}\n\n${skill.body.trim()}\n`
      writeFileSync(join(out, `${domain.name}-${skill.name}.md`), content)
      built.push({ file: `dist/chatgpt/${domain.name}-${skill.name}.md`, tokens: estimateTokens(content) })
    }

    const pack =
      preamble(`my-staff / ${domain.name}`, 'Generated by `staff build chatgpt`.') +
      `# ${domain.name}\n\n${domain.manifest?.summary ?? ''}\n\n` +
      `Each section below is one procedure. Follow the one whose "Use this when" matches the request.\n\n` +
      skills
        .map((skill) => `---\n\n## ${skill.name}\n\n**Use this when:** ${skill.data.description}\n\n${skill.body.trim()}`)
        .join('\n\n') +
      '\n'
    const file = `dist/chatgpt/${domain.name}.md`
    writeFileSync(join(out, `${domain.name}.md`), pack)
    built.push({ file, tokens: estimateTokens(pack), warn: estimateTokens(pack) > CHATGPT_TOKEN_WARN })
  }
  return { built, refused: [] }
}

/** Codex slash commands. Self-contained, so the prompt works whether or not the skill is installed. */
export function buildCodexPrompts(repo, { outDir = join(repo.root, 'dist', 'codex-prompts') } = {}) {
  const out = freshDirectory(outDir)
  const built = []
  for (const { skill } of allSkills(repo)) {
    if (!skill.exists || skill.data === null) continue
    const content = `${skill.body.trim()}\n`
    writeFileSync(join(out, `${skill.name}.md`), content)
    built.push({ file: `dist/codex-prompts/${skill.name}.md`, tokens: estimateTokens(content) })
  }
  return { built, refused: [], note: 'Copy into ~/.codex/prompts/ to get them as slash commands.' }
}

export const TARGETS = {
  'claude-ai': buildClaudeAi,
  chatgpt: buildChatgpt,
  'codex-prompts': buildCodexPrompts,
}

export function build(repo, target) {
  if (target === 'all') {
    const results = Object.entries(TARGETS).map(([name, run]) => [name, run(repo)])
    return {
      built: results.flatMap(([, result]) => result.built),
      refused: results.flatMap(([, result]) => result.refused),
    }
  }
  const run = TARGETS[target]
  if (!run) throw new Error(`Unknown target "${target}". Use ${Object.keys(TARGETS).join(', ')} or all.`)
  return run(repo)
}
