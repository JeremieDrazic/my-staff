import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { FAMILY_LABELS, FAMILY_ORDER } from './model.mjs'

const STATUS = { ready: '`ready`', draft: '`draft`', deprecated: '~~`deprecated`~~' }
const SHAPE = { builder: 'builder', reviewer: 'reviewer', advisor: 'advisor' }

const escapePipes = (text) => String(text).replace(/\|/g, '\\|')

function block(key, body) {
  return `<!-- staff:${key} -->\n${body}\n<!-- /staff:${key} -->`
}

export function renderDomains(repo) {
  const lines = []
  for (const family of FAMILY_ORDER) {
    const domains = repo.domains
      .filter((domain) => domain.manifest?.family === family)
      .sort((a, b) => a.name.localeCompare(b.name))
    if (domains.length === 0) continue
    lines.push(`### ${FAMILY_LABELS[family]}`, '')
    lines.push('| Domain | What it covers | Skills | Roles | Status |')
    lines.push('| :- | :- | -: | -: | :- |')
    for (const domain of domains) {
      const status = STATUS[domain.manifest.status] ?? domain.manifest.status
      const name = domain.manifest.status === 'deprecated' ? `~~\`${domain.name}\`~~` : `\`${domain.name}\``
      lines.push(
        `| ${name} | ${escapePipes(domain.manifest.summary)} | ${domain.skills.filter((s) => s.exists).length} | ${domain.agents.length} | ${status} |`,
      )
    }
    lines.push('')
  }
  return lines.join('\n').trimEnd()
}

export function renderRoles(repo) {
  const rows = []
  for (const domain of repo.domains) {
    for (const agent of domain.agents) {
      rows.push(`| \`${agent.name}\` | ${SHAPE[agent.shape]} | \`${domain.name}\` | ${escapePipes(agent.data?.description?.split(/(?<=\.)\s/)[0] ?? '')} |`)
    }
  }
  if (rows.length === 0) return '_No role yet._'
  return ['| Role | Shape | Domain | What it does |', '| :- | :- | :- | :- |', ...rows].join('\n')
}

export function renderStats(repo) {
  const skills = repo.domains.reduce((total, domain) => total + domain.skills.filter((s) => s.exists).length, 0)
  const roles = repo.domains.reduce((total, domain) => total + domain.agents.length, 0)
  const checklists = repo.domains.reduce((total, domain) => total + domain.checklists.length, 0)
  const ready = repo.domains.filter((domain) => domain.manifest?.status === 'ready').length
  return `**${skills}** skills · **${roles}** roles · **${checklists}** checklists · **${ready}** of ${repo.domains.length} domains ready`
}

function renderDomainReadme(domain) {
  const { manifest } = domain
  const lines = [
    `# ${domain.name}`,
    '',
    `${manifest.summary}`,
    '',
    `Status: ${STATUS[manifest.status] ?? manifest.status} · version ${manifest.version} · family ${FAMILY_LABELS[manifest.family]}`,
    '',
    '> Generated by `staff readme` from `domain.json` and this directory. Edit those, not this file.',
    '',
    '## Install',
    '',
    '```bash',
    `npx skills add jeremiedrazic/my-staff --skill <skill-name>   # ~70 agents`,
    `claude plugin marketplace add jeremiedrazic/my-staff && claude plugin install ${domain.name}@my-staff`,
    '```',
    '',
  ]

  const skills = domain.skills.filter((skill) => skill.exists)
  if (skills.length > 0) {
    lines.push('## Skills', '', '| Skill | When to use it |', '| :- | :- |')
    for (const skill of skills) {
      lines.push(`| [\`${skill.name}\`](skills/${skill.name}/SKILL.md) | ${escapePipes(skill.data?.description ?? '')} |`)
    }
    lines.push('')
  }
  if (domain.agents.length > 0) {
    lines.push('## Roles', '', '| Role | Shape | What it does |', '| :- | :- | :- |')
    for (const agent of domain.agents) {
      lines.push(`| [\`${agent.name}\`](agents/${agent.file}) | ${SHAPE[agent.shape]} | ${escapePipes(agent.data?.description ?? '')} |`)
    }
    lines.push('')
  }
  if (domain.checklists.length > 0) {
    lines.push('## Checklists', '')
    for (const checklist of domain.checklists) {
      lines.push(`- [\`${checklist.name}\`](checklists/${checklist.name}/00-index.md) — ${checklist.sections.length} sections`)
    }
    lines.push('')
  }
  if (manifest.requires?.length) {
    lines.push('## External tools this domain delegates to', '')
    for (const dependency of manifest.requires) {
      const link = dependency.url ? `[${dependency.name}](${dependency.url})` : dependency.name
      lines.push(`- **${link}** — owns ${dependency.covers.join(', ')}. Install: \`${dependency.install}\``)
    }
    lines.push('')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

export function buildReadmes(repo) {
  const files = []
  const readmePath = join(repo.root, 'README.md')
  if (existsSync(readmePath)) {
    let text = readFileSync(readmePath, 'utf8')
    const blocks = { domains: renderDomains(repo), roles: renderRoles(repo), stats: renderStats(repo) }
    for (const [key, body] of Object.entries(blocks)) {
      const pattern = new RegExp(`<!-- staff:${key} -->[\\s\\S]*?<!-- /staff:${key} -->`)
      if (pattern.test(text)) text = text.replace(pattern, block(key, body))
    }
    files.push({ path: 'README.md', content: text })
  }
  for (const domain of repo.domains) {
    if (!domain.manifest) continue
    files.push({ path: `domains/${domain.name}/README.md`, content: renderDomainReadme(domain) })
  }
  return files
}

export function writeReadmes(repo) {
  const written = []
  for (const file of buildReadmes(repo)) {
    const target = join(repo.root, file.path)
    if (existsSync(target) && readFileSync(target, 'utf8') === file.content) continue
    writeFileSync(target, file.content)
    written.push(file.path)
  }
  return written
}

export function checkReadmes(repo) {
  return buildReadmes(repo)
    .filter((file) => {
      const target = join(repo.root, file.path)
      return !existsSync(target) || readFileSync(target, 'utf8') !== file.content
    })
    .map((file) => ({ level: 'error', code: 'readme/stale', file: file.path, message: 'Out of date. Run `staff readme`.' }))
}
